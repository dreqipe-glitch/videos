"""Builds hf/compositions/captions.html from the forced-aligned words (timing/words-aligned-full.json).
Captions only cover the real footage: 0.9667–5.2333 (after the title card), 6.6667–19.8667, 55.8–70.0333 s.
Spelling follows the reference script; captions carry words only, no punctuation."""
import json, html, pathlib
here = pathlib.Path(__file__).parent
A = {w["i"]: w for w in json.load(open(here / "words-aligned-full.json"))}

# (script spelling, aligned word index or (index, share) for a word split across one spoken token)
SECTIONS = [
  (29 / 30, 157 / 30, [
    [("واش", 2), ("عناصر", 3), ("الدرك", 4), ("الملكي", 5)],
    [("عندهن", 6), ("الحق", 7), ("يفتشوا", 8), ("امرأة؟", 9)],
  ]),
  (200 / 30, 596 / 30, [
    [("أن", 15), ("حضور", 16), ("المرأة", 17)],
    [("في", 18), ("جهاز", 19), ("الدرك", 20), ("الملكي", 21)],
    [("هو", 22), ("مجرد", 23), ("حضور", 24)],
    [("بالزي", 25), ("الرسمي", 26), ("صافي..", 27)],
    [("والواقع", 28), ("العكس", 29), ("تماماً!", 30)],
    [("نساء", 31), ("الدرك", 32), ("الملكي", 33)],
    [("مسؤولية،", 34), ("انضباط،", 35)],
    [("وحزم", 36), ("في", 37), ("أصعب", 38), ("المواقف.", 39)],
  ]),
  (1674 / 30, 2101 / 30, [
    [("تحية", 109), ("تقدير", 110), ("واعتراف", 111)],
    [("لكل", 112), ("نساء", 113), ("الدرك", 114), ("الملكي", 115), ("المغربي،", 116)],
    [("اللي", 117), ("واقفين", 118), ("سَدْ", 119), ("منيع", 120)],
    [("في", 121), ("خدمة", 122), ("الوطن", 123), ("والمواطنين.", 124)],
    [("ودابا،", (125, 126)), ("دوركم", 127), ("أَنْتُمْ:", 128)],
    [("واش", 129), ("كنتو", 130), ("عارفين", 131)],
    [("هذه", (132, 0)), ("التفاصيل", (132, 1)), ("القانونية", 133)],
    [("والأدوار", 134), ("اللي", 135), ("كتقوم", 136), ("بها", 137)],
    [("المرأة", 138), ("داخل", 139), ("جهاز", 140), ("الدرك؟", 141)],
  ]),
]

def span(ref):
    if isinstance(ref, int): return A[ref]["start"], A[ref]["end"]
    a, b = ref
    if b in (0, 1) and a == 132:  # «هالتفاصيل» spoken as one word: split «هذه | التفاصيل» 35/65
        s, e = A[a]["start"], A[a]["end"]; m = s + (e - s) * 0.35
        return (s, m) if b == 0 else (m, e)
    return A[a]["start"], A[b]["end"]

PUNCT = "،,.:؛;!؟?…"
strip = lambda t: "".join(ch for ch in t if ch not in PUNCT)

groups = []
for s0, s1, gs in SECTIONS:
    sec = []
    for g in gs:
        words = [(strip(t), *span(r)) for t, r in g]
        sec.append(words)
    for k, words in enumerate(sec):
        op = max(s0, words[0][1] - 0.08)
        nxt = sec[k + 1][0][1] - 0.08 if k + 1 < len(sec) else s1
        cl = min(nxt, words[-1][2] + 0.4, s1)
        groups.append((round(op, 3), round(cl, 3), words))

out = []
js = []
for gi, (op, cl, words) in enumerate(groups):
    spans = " ".join(f'<span class="cw" id="cap-w{gi}-{wi}">{html.escape(t)}</span>' for wi, (t, _, _) in enumerate(words))
    out.append(f'    <div class="cap-g clip" id="cap-g{gi}" data-start="{op}" data-duration="{round(cl - op, 3)}"><div class="cap-pill" id="cap-p{gi}">{spans}</div></div>')
    js.append({"g": gi, "op": op, "cl": cl, "w": [[round(s, 3), round(e, 3)] for _, s, e in words]})

doc = f'''<template>
  <style>
    #root {{ position: absolute; inset: 0; }}
    .cap-g {{ position: absolute; left: 90px; right: 120px; top: 1230px; height: 220px; display: flex; align-items: flex-end; justify-content: center; direction: rtl; }}
    .cap-pill {{ display: inline-block; max-width: 840px; text-align: center; padding: 6px 34px 16px; border-radius: 28px; background: rgba(5,8,15,0.72);
      box-shadow: 0 10px 34px rgba(0,0,0,0.35); font-family: var(--font-ar); font-weight: 700; font-size: 66px; line-height: 1.42; color: var(--ink); text-shadow: 0 2px 10px rgba(0,0,0,0.55); }}
    .cw {{ display: inline-block; }}
  </style>
  <div id="root" data-composition-id="captions" data-start="0" data-duration="79.4" data-width="1080" data-height="1920">
{chr(10).join(out)}
  </div>
  <script>
    (function () {{
      // generated by timing/build_captions.py from the forced-aligned word timings
      const G = {json.dumps(js)};
      const tl = gsap.timeline({{ paused: true }});
      G.forEach(({{ g, op, cl, w }}) => {{
        const pill = "#cap-p" + g;
        tl.fromTo(pill, {{ opacity: 0, y: 18, scale: 0.97 }}, {{ opacity: 1, y: 0, scale: 1, duration: 0.14, ease: "power3.out" }}, op);
        tl.to(pill, {{ opacity: 0, duration: 0.08, ease: "power2.in" }}, cl - 0.08);
        w.forEach(([s, e], i) => {{
          const el = "#cap-w" + g + "-" + i;
          const off = i + 1 < w.length ? w[i + 1][0] : Math.min(e + 0.25, cl);
          tl.fromTo(el, {{ color: "#F4F1EA" }}, {{ color: "#C9A227", duration: 0.06, ease: "none", immediateRender: false }}, s);
          tl.to(el, {{ color: "#F4F1EA", duration: 0.06, ease: "none" }}, Math.max(s + 0.06, off - 0.03));
        }});
      }});
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
'''
(here.parent / "hf/compositions/captions.html").write_text(doc)
for op, cl, words in groups: print(f"{op:6.2f}-{cl:6.2f}  " + " ".join(w[0] for w in words))
